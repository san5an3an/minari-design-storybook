export function loadDemos(slug: string): Promise<DemoModule> | null {
  if (!SLUGS.has(slug)) return null;
  return import(`./${slug}`).then((m) => ({
    demos: m.DEMOS,
    skipped: m.SKIPPED,
  }) as DemoModule);
}
