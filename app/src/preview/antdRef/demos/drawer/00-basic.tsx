import React, { useState } from 'react';
import { Button, Drawer } from 'antd';

const App: React.FC = () => {
  const [open, setOpen] = useState(false);

  const showDrawer = () => {
    setOpen(true);
  };

  const onClose = () => {
    setOpen(false);
  };

  return (
    <>
      <Button type="primary" onClick={showDrawer}>
        열기
      </Button>
      <Drawer
        title="기본 서랍"
        closable={{ 'aria-label': '닫기 버튼' }}
        onClose={onClose}
        open={open}
      >
        <p>내용이 들어가요…</p>
        <p>내용이 들어가요…</p>
        <p>내용이 들어가요…</p>
      </Drawer>
    </>
  );
};

export default App;